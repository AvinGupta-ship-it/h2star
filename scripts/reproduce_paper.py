"""Regenerate every number and figure the manuscript uses (D10).

From a fresh clone:
    python3 scripts/run_identifiability.py      (slow; writes analysis JSON)
    python3 scripts/run_uq_mcmc.py              (slow; writes posterior/diag)
    python3 scripts/run_sensitivity.py          (writes sensitivity JSON)
    python3 scripts/run_observable_map.py       (writes map JSON)
    python3 scripts/make_figures_v1.py          (figures from the JSONs)
    python3 scripts/reproduce_paper.py          (this file: gates + macros)

This script re-derives the gate numbers directly from the frozen model (they
must equal the adjudicated records to the quoted digits) and emits
manuscript/generated_numbers.tex. The manuscript compiles ONLY against that
macro file; tests/test_manuscript_numbers.py fails if a committed macro
disagrees with a regenerated one. Pass --check to compare without writing.
"""

import functools
import json
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
from h2star import engineering as eng  # noqa: E402
from h2star import eos, isotherm  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..")
AN = os.path.join(ROOT, "data", "analysis")
OUT = os.path.join(ROOT, "manuscript", "generated_numbers.tex")

eos.density = functools.lru_cache(maxsize=4096)(eos.density)


def gate_numbers():
    p = eng.EngineeringParamsV1.from_yaml(
        os.path.join(ROOT, "data", "engineering_v1.yaml"))
    mof5 = isotherm.Material.from_yaml(
        os.path.join(ROOT, "data", "materials", "mof5_hsecoe.yaml"))
    ax21 = isotherm.Material.from_yaml(
        os.path.join(ROOT, "data", "materials", "ax21.yaml"))
    hex_ = eng.evaluate_sized(eng.SystemDesignV1(
        mof5, isotherm.ModifiedDA(mof5), p, "type1", 100e5, 80.0, 5e5, 140.0))
    h12 = eng.evaluate_sized(eng.SystemDesignV1(
        ax21, isotherm.ModifiedDA(ax21), p, "type3", 200e5, 80.0, 5e5, 160.0))
    h3 = eng.evaluate_sized(eng.SystemDesignV1(
        ax21, isotherm.ModifiedDA(ax21), p, "type1", 60e5, 40.0, 5e5, 110.0))
    return hex_, h12, h3


def main():
    check = "--check" in sys.argv
    hex_, h12, h3 = gate_numbers()
    with open(os.path.join(AN, "identifiability_v1.json")) as fh:
        ID = json.load(fh)
    with open(os.path.join(AN, "uq_mcmc_v1.json")) as fh:
        MC = json.load(fh)
    with open(os.path.join(AN, "sensitivity_v1.json")) as fh:
        SE = json.load(fh)
    with open(os.path.join(AN, "observable_map_v1.json")) as fh:
        OM = json.load(fh)
    with open(os.path.join(AN, "bop_anchor_sensitivity.json")) as fh:
        BA = json.load(fh)["variants"]

    m77 = ID["single_isotherm_77K"]["profiles"]
    mmt = ID["multi_temperature"]["profiles"]
    prop77 = [r for r in ID["propagation_baseline_envelope_77K"]
              if r.get("in_frozen")]
    gcs = [r["GC"] for r in prop77]
    # Region-wide spread: ridge trace plus the exact n_max interval
    # endpoints (referee R2, M2). The 77 K optimum sits on the ridge trace.
    gcs_full = gcs + [r["GC"]
                      for r in ID["propagation_77K_interval_endpoints"]]
    sh = SE["shapley"]
    var = sh["var_GC"]
    top = sorted(sh["GC"], key=lambda k: -sh["GC"][k][0])[:3]
    rho_idx = OM["rho_grid"].index(500.0)

    def M(name, value):
        return f"\\newcommand{{\\{name}}}{{{value}}}\n"

    tex = "% generated by scripts/reproduce_paper.py; never edit by hand\n"
    tex += M("vEOneMsys", f"{hex_['m_sys']:.2f}")
    tex += M("vEOneVsys", f"{hex_['V_sys'] * 1e3:.2f}")
    tex += M("vEOneTwall", f"{hex_['t_wall'] * 1e3:.2f}")
    tex += M("vEtwoGC", f"{h12['GC']:.4f}")
    tex += M("vEtwoVC", f"{h12['VC']:.4f}")
    tex += M("vEtwoGCdev", f"{100 * (h12['GC'] / 0.0339 - 1):.0f}")
    tex += M("vEtwoVCdev", f"{100 * (h12['VC'] / 0.0210 - 1):.1f}")
    tex += M("vHthreeM", f"{h3['m_sys']:.1f}")
    tex += M("vHthreeV", f"{h3['V_sys'] * 1e3:.1f}")
    tex += M("vHthreeMdev", f"{100 * (h3['m_sys'] / 99.8 - 1):.1f}")
    tex += M("vHthreeVdev", f"{100 * (h3['V_sys'] * 1e3 / 206.6 - 1):.1f}")
    tex += M("vNmaxLoA", f"{m77['n_max']['interval_frozen'][0]:.0f}")
    tex += M("vNmaxHiA", f"{m77['n_max']['interval_frozen'][1]:.0f}")
    tex += M("vLpLoA", f"{m77['log10_p0']['interval_frozen'][0]:.2f}")
    tex += M("vLpHiA", f"{m77['log10_p0']['interval_frozen'][1]:.0f}")
    tex += M("vNmaxLoM", f"{mmt['n_max']['interval_frozen'][0]:.1f}")
    tex += M("vNmaxHiM", f"{mmt['n_max']['interval_frozen'][1]:.1f}")
    tex += M("vLpLoM", f"{mmt['log10_p0']['interval_frozen'][0]:.2f}")
    tex += M("vLpHiM", f"{mmt['log10_p0']['interval_frozen'][1]:.2f}")
    tex += M("vObjDof",
             f"{ID['multi_temperature']['overdispersion_s2']:.2f}")
    tex += M("vGCpropLo", f"{min(gcs):.4f}")
    tex += M("vGCpropHi", f"{max(gcs):.4f}")
    tex += M("vGCpropPct",
             f"{100 * (max(gcs) - min(gcs)) / (max(gcs) + min(gcs)):.1f}")
    tex += M("vGCfullPct",
             f"{100 * (max(gcs_full) - min(gcs_full)) / (max(gcs_full) + min(gcs_full)):.1f}")
    tex += M("vGCendLowDev",
             f"{100 * (1 - min(gcs_full) / max(gcs_full)):.1f}")
    tex += M("vESSmin", f"{math.floor(min(MC['ess'].values()))}")
    tex += M("vRhatMax", f"{max(MC['rhat'].values()):.4f}")
    tex += M("vObjMtwo", f"{MC['model_forms']['mda_m2']['objective']:.1f}")
    tex += M("vObjFreeM",
             f"{MC['model_forms']['mda_free_m']['objective']:.1f}")
    tex += M("vFreeM", f"{MC['model_forms']['mda_free_m']['m']:.2f}")
    tex += M("vObjToth", f"{MC['model_forms']['toth']['objective']:.1f}")
    tex += M("vGCmean", f"{SE['distribution']['GC']['mean']:.4f}")
    tex += M("vGCsd", f"{SE['distribution']['GC']['sd']:.4f}")
    tex += M("vShOne", top[0].replace('_', '\\_'))
    tex += M("vShOneShare", f"{sh['GC'][top[0]][0] / var:.2f}")
    tex += M("vShTwo", top[1].replace('_', '\\_'))
    tex += M("vShTwoShare", f"{sh['GC'][top[1]][0] / var:.2f}")
    tex += M("vShMat", f"{sh['GC']['material'][0] / var:.3f}")
    tex += M("vShMatSE", f"{sh['GC']['material'][1] / var:.3f}")
    tex += M("vUreqVone",
             f"{OM['models']['v1_component']['u_required_2025'][rho_idx]:.3f}")
    tex += M("vUreqVzero",
             f"{OM['models']['v02_lumped']['u_required_2025'][rho_idx]:.3f}")
    tex += M("vAxUd",
             f"{OM['ax21_point']['deliverable_uptake_excess_swing']:.3f}")
    abs_ref = OM["ax21_point"]["deliverable_uptake_abs_swing_reference_only"]
    tex += M("vAxUdAbs", f"{abs_ref:.3f}")
    tex += M("vAmbientVint",
             f"{SE['ambient_298K_contrast']['V_internal_L']:.0f}")
    tex += M("vEtwoGCdevCorr", f"{BA['corrected']['E2']['H1_dev_pct']:.0f}")
    tex += M("vEtwoGCdevFixed", f"{BA['fixed']['E2']['H1_dev_pct']:.0f}")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if check:
        with open(OUT) as fh:
            committed = fh.read()
        if committed != tex:
            import difflib
            sys.stdout.writelines(difflib.unified_diff(
                committed.splitlines(True), tex.splitlines(True),
                "committed", "regenerated"))
            sys.exit(1)
        print("generated_numbers.tex matches the regenerated values")
    else:
        with open(OUT, "w") as fh:
            fh.write(tex)
        print("wrote", OUT)


if __name__ == "__main__":
    main()
